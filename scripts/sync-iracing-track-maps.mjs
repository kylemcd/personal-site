import {
	copyFile,
	mkdir,
	mkdtemp,
	readFile,
	rm,
	writeFile,
} from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";

import { uploadRacingTrackMapDirectory } from "./upload-racing-track-maps.mjs";

const metadataUrl =
	"https://raw.githubusercontent.com/meowmachine/racing-track-maps-vector/main/from-iracing/iracing-tracks-metadata.json";
const layers = [
	"background",
	"active",
	"inactive",
	"pitroad",
	"start-finish",
	"turns",
];
const temporaryDirectory = await mkdtemp(
	path.join(tmpdir(), "kpm-iracing-track-maps-"),
);
const outputDirectory = path.join(temporaryDirectory, "iracing");
const generatedIdsPath = path.resolve(
	"src/lib/garage61/track-map-ids.generated.ts",
);
const sourceArgument = process.argv.find((argument) =>
	argument.startsWith("--source="),
);
const localSourceDirectory = sourceArgument
	? path.resolve(sourceArgument.slice("--source=".length))
	: null;

const parseMetadata = (raw) => JSON.parse(raw.replace(/^\uFEFF/, ""));

async function loadMetadata() {
	if (localSourceDirectory) {
		return parseMetadata(
			await readFile(
				path.join(localSourceDirectory, "iracing-tracks-metadata.json"),
				"utf8",
			),
		);
	}

	const response = await fetch(metadataUrl);
	if (!response.ok) {
		throw new Error(
			`Could not fetch iRacing track metadata (${response.status}).`,
		);
	}
	return parseMetadata(await response.text());
}

async function writeLayer(configuration, layer) {
	const configurationDirectory = path.join(
		outputDirectory,
		String(configuration.track_id),
	);
	await mkdir(configurationDirectory, { recursive: true });
	const destination = path.join(configurationDirectory, `${layer}.svg`);

	if (localSourceDirectory) {
		await copyFile(
			path.join(
				localSourceDirectory,
				...configuration.svg_local_path.split("/"),
				`${layer}.svg`,
			),
			destination,
		);
		return;
	}

	const response = await fetch(configuration.svg_urls[layer]);
	if (!response.ok) {
		throw new Error(
			`Could not fetch track ${configuration.track_id} ${layer}.svg (${response.status}).`,
		);
	}
	await writeFile(destination, Buffer.from(await response.arrayBuffer()));
}

async function runWithConcurrency(tasks, concurrency) {
	let nextIndex = 0;
	async function worker() {
		while (nextIndex < tasks.length) {
			const task = tasks[nextIndex];
			nextIndex += 1;
			await task();
		}
	}
	await Promise.all(Array.from({ length: concurrency }, () => worker()));
}

const metadata = await loadMetadata();
const configurations = metadata.tracks.flatMap((track) =>
	track.configurations.map((configuration) => ({
		...configuration,
		track_name: track.track_name.trim(),
	})),
);
const tasks = configurations.flatMap((configuration) =>
	layers.map((layer) => () => writeLayer(configuration, layer)),
);

await mkdir(outputDirectory, { recursive: true });
await runWithConcurrency(tasks, localSourceDirectory ? 32 : 12);
await writeFile(
	path.join(outputDirectory, "catalog.json"),
	`${JSON.stringify(
		{
			source: metadataUrl,
			generatedAt: metadata.generated_at,
			configurations: Object.fromEntries(
				configurations.map((configuration) => [
					configuration.track_id,
					{
						track: configuration.track_name,
						layout: configuration.config_name ?? null,
					},
				]),
			),
		},
		null,
		2,
	)}\n`,
);

const sortedTrackIds = configurations
	.map((configuration) => configuration.track_id)
	.sort((a, b) => a - b);
const idLines = [];
for (let index = 0; index < sortedTrackIds.length; index += 16) {
	idLines.push(`\t${sortedTrackIds.slice(index, index + 16).join(", ")},`);
}
await writeFile(
	generatedIdsPath,
	`// Generated by scripts/sync-iracing-track-maps.mjs.\n// biome-ignore format: Keep generated output stable between syncs.\nconst availableTrackMapIds = new Set<number>([\n${idLines.join("\n")}\n]);\n\nexport { availableTrackMapIds };\n`,
);

const uploadResult = await uploadRacingTrackMapDirectory({
	directory: outputDirectory,
});
await rm(temporaryDirectory, { recursive: true, force: true });

console.log(
	`Synced ${configurations.length} configurations and ${uploadResult.svgCount} SVG files to R2.`,
);
